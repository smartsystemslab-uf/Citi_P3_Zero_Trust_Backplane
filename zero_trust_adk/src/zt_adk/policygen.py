"""Generated PSL policy store of a protection bundle.

PSL is the only policy container: everything the Backplane decides at run time is a rule of
this store, compiled and type-checked against the store's field catalogue and signed with
the deployment's policy key.

Files (``policy_store/``):

  policy_fields.yaml   field catalogue: base scopes + the argument fields of every tool +
                       the content-detector families of the profile
  00_core.psl          approvals for critical operations (per resource, from classification
                       and zt_adk.yaml), separation of duty of the two approvers, approval for
                       any operation of critical risk (e.g. side effects after a flagged tool
                       result in the same run)
  10_access.psl        least privilege: one @permit per generated PEP placement (who may route
                       to which agent, call which tool, use which built-in capability, enter
                       the system, emit output) -- everything else is denied by default
  20_identity.psl      SPIFFE scheme B checks at the PDP (distributed runtime) and the
                       in-process plugin's authentication scheme
  30_content.psl       input / output / agent-message / tool-result / tool-call / model-request
                       rules from the profile (deny or flag)
  40_workflow.psl      temporal rules over each run: steps of sequential workflows in order
  50_gateway_runtime.psl  temporal properties of the distributed gateway's tool path
  overlays/*.psl       the system owner's own rules (copied unchanged; they compile against
                       the same catalogue)
"""
from __future__ import annotations

import copy
import fnmatch
import glob
import re
from dataclasses import dataclass, field
from importlib import resources
from pathlib import Path
from typing import Any

import yaml

from . import model as M
from .manifest import INGRESS_SUBJECT, IdMaps, INPUT_RESOURCE, OUTPUT_RESOURCE
from .profile import Profile

ARG_NAME = re.compile(r"^[A-Za-z_][A-Za-z0-9_]{0,63}$")


class PolicyGenerationError(ValueError):
    pass


def _lit(value: str) -> str:
    v = str(value)
    if '"' in v or "\\" in v or "\n" in v:
        raise PolicyGenerationError(f"value cannot be used in a PSL string literal: {v!r}")
    return f'"{v}"'


def _rid(text: str) -> str:
    """Rule id fragment (annotation value)."""
    return re.sub(r"[^A-Za-z0-9_.-]+", "_", text).strip("_")[:120]


def _nl(text: str) -> str:
    return " ".join(str(text).split())[:600]


def _header(title: str, set_id: str, version: str, source: str, runtime: str | None = None) -> list[str]:
    lines = [f"// {title}", f"// Generated by zt-adk ({source}). Do not edit: rebuild the bundle instead.", "",
             f"// @policy_set {set_id}", f"// @version {version}", f"// @source {source}"]
    if runtime:
        lines.append(f"// @runtime {runtime}")
    return lines


@dataclass
class GeneratedStore:
    files: dict[str, str] = field(default_factory=dict)          # name -> text
    rules: dict[str, list[str]] = field(default_factory=dict)    # file -> rule ids
    argument_fields: list[str] = field(default_factory=list)
    warnings: list[str] = field(default_factory=list)


def _argument_names(model: M.SystemModel) -> list[str]:
    names: set[str] = set()
    for tool in model.tools.values():
        if tool.kind in (M.BUILTIN, M.AGENT_TOOL):
            continue
        for name in (tool.parameters.get("properties") or {}):
            if ARG_NAME.match(name) and name not in {"well_formed"}:
                names.add(name)
    return sorted(names)


def build_catalog(model: M.SystemModel, profile: Profile) -> tuple[dict[str, Any], list[str]]:
    base = yaml.safe_load(resources.files("zt_adk").joinpath("resources/fields_base.yaml").read_text("utf-8"))
    cat = copy.deepcopy(base)
    pdp = cat["scopes"]["pdp_request"]["fields"]
    added: list[str] = []
    for name in _argument_names(model):
        for suffix, ftype, src in (("", "string", "str(parameters.{p}) ('' when absent)"),
                                   (".length", "int", "len(parameters.{p}) when text, else 0"),
                                   (".nonempty", "bool", "parameters.{p} is non-blank text"),
                                   (".finite_nonzero", "bool", "parameters.{p} is a finite number != 0")):
            fname = f"args.{name}{suffix}"
            pdp[fname] = {"type": ftype, "source": "PDP checker: " + src.format(p=name)}
            added.append(fname)
    return cat, added


def _access_file(model: M.SystemModel, ids: IdMaps, plan: dict[str, Any], profile: Profile) -> tuple[str, list[str]]:
    lines = _header("Least-privilege access: one permission per generated PEP placement.",
                    "zt_adk.access", "1.0.0", "zt-adk build: PEP plan of the discovered system")
    lines += ["vunit access (pdp_request) {", ""]
    rule_ids: list[str] = []
    seen: set[tuple[str, str, str, str]] = set()
    ops_by_resource = {ids.tool_resource[k]: (k, v) for k, v in ids.operations.items()}
    for i, pep in enumerate(sorted(plan.get("logical_peps", []), key=lambda p: p["placement_id"])):
        subject, resource, action = pep["subject_canonical_id"], pep["resource_canonical_id"], pep["action"]
        workflow = pep.get("workflow_id") or ""
        key = (subject, resource, action, workflow)
        if key in seen:
            continue
        seen.add(key)
        rid = f"access.{_rid(pep['placement_id'].removeprefix('pep.'))}"
        rule_ids.append(rid)
        obligations = [f"enhanced_logging(reason=zt_adk_{pep['pep_type']})"]
        nl = f"{subject} may {action} {resource}"
        if resource in ops_by_resource:
            _key, op = ops_by_resource[resource]
            if op["side_effect"]:
                obligations.append("require_idempotency_key")
            if op.get("mask_fields"):
                obligations.append(f"data_masking(fields=[{', '.join(op['mask_fields'])}])")
        nl += f" in workflow {workflow}" if workflow else " outside any workflow"
        lines += [f"  // @rule {rid}", f"  // @nl {_nl(nl)}.", "  // @permit"]
        lines += [f"  // @obligation {o}" for o in obligations]
        cond = [f"subject.id == {_lit(subject)}", f"resource.id == {_lit(resource)}", f"action == {_lit(action)}",
                f"workflow.id == {_lit(workflow)}"]
        lines += [f"  property permit_{i} = " + "\n      && ".join(cond) + ";", ""]
    lines += ["}", ""]
    return "\n".join(lines), rule_ids


def _core_file(model: M.SystemModel, ids: IdMaps, profile: Profile,
               approval_issuers: list[str], secondary_issuers: list[str]) -> tuple[str, list[str]]:
    lines = _header("Approvals for critical operations.", "zt_adk.core", "1.0.0",
                    "zt-adk build: operation classification + zt_adk.yaml")
    lines += ["vunit core (pdp_request) {", ""]
    rule_ids: list[str] = []
    n = 0
    for key, op in sorted(ids.operations.items()):
        if not op.get("requires_approval"):
            continue
        resource = ids.tool_resource[key]
        need = "approval.valid && approval.secondary_valid" if op.get("secondary_approval") else "approval.valid"
        rid = f"core.approval.{_rid(key.replace('/', '.'))}"
        rule_ids.append(rid)
        who = "a human approval and an independent secondary authorization" if op.get("secondary_approval") \
            else "a human approval"
        text = f"{key} ({op['action']}, {op['criticality']}) runs only with {who} bound to this exact request"
        lines += [f"  // @rule {rid}",
                  f"  // @nl {_nl(text)}.",
                  "  // @on_violation MANUAL_REVIEW",
                  f"  approval_{n}: assert always (authz_request && resource.id == {_lit(resource)} -> {need});", ""]
        n += 1
    rid = "core.critical_risk_requires_approval"
    rule_ids.append(rid)
    lines += [f"  // @rule {rid}",
              "  // @nl An operation assessed at critical risk (a critical operation, or a side effect after a tool "
              "result or agent message of the same run was flagged) runs only with a human approval.",
              "  // @on_violation MANUAL_REVIEW",
              "  critical_risk: assert always (authz_request && risk.level == \"critical\" -> approval.valid);", ""]
    for j, issuer in enumerate(sorted(set(approval_issuers) & set(secondary_issuers))):
        rid = f"core.separation_of_duty.{_rid(issuer)}"
        rule_ids.append(rid)
        lines += [f"  // @rule {rid}",
                  "  // @nl The secondary authorization must come from a different approver than the approval.",
                  f"  separation_{j}: assert never (authz_request && approval.issuer == {_lit(issuer)} "
                  f"&& approval.secondary_issuer == {_lit(issuer)});", ""]
    lines += ["}", ""]
    return "\n".join(lines), rule_ids


def _identity_file() -> tuple[str, list[str]]:
    lines = _header("Authenticated identity at the PDP.", "zt_adk.identity", "1.0.0", "zt-adk")
    lines += [
        "vunit identity (pdp_request) {", "",
        "  // @rule identity.spiffe-b-agent-verified",
        "  // @nl A request the gateway authenticated with SPIFFE scheme B as an agent is decided only if both "
        "factors (workload SVID, agent credential) were verified and the assertion names the request's agent.",
        "  spiffe_b_agent: assert always (authz_request && auth.scheme == \"B\" && auth.subject_kind == \"agent\"",
        "      -> auth.factor.workload_identity && auth.factor.agent_credential && auth.agent_bound);", "",
        "  // @rule identity.spiffe-b-service-io-only",
        "  // @nl A caller authenticated as a service (ingress) obtains decisions only for the input and output "
        "channels and for entering an agent, never for a tool.",
        "  spiffe_b_service: assert always (authz_request && auth.scheme == \"B\" && auth.subject_kind == \"service\"",
        "      -> auth.factor.workload_identity && (resource.runtime_id == \"mas_input_channel\"",
        "         || resource.runtime_id == \"mas_output_channel\" || resource.target_type == \"subject\"));", "",
        "  // @rule identity.known-subject-kind",
        "  // @nl An authentication result names its subject kind (agent or service).",
        "  known_kind: assert never (authz_request && (auth.scheme == \"B\" || auth.scheme == \"P\")",
        "      && auth.subject_kind != \"agent\" && auth.subject_kind != \"service\");", "",
        "  // @rule identity.plugin-agent-bound",
        "  // @nl A request built by the in-process plugin for an agent names that agent in its signed assertion.",
        "  plugin_agent: assert always (authz_request && auth.scheme == \"P\" && auth.subject_kind == \"agent\"",
        "      -> auth.agent_bound);", "",
        "  // @rule identity.authenticated",
        "  // @nl Every request carries an authentication assertion of the plugin or the gateway.",
        "  authenticated: assert always (authz_request -> (auth.scheme == \"B\" || auth.scheme == \"P\"));", "",
        "}", ""]
    rules = ["identity.spiffe-b-agent-verified", "identity.spiffe-b-service-io-only", "identity.known-subject-kind",
             "identity.plugin-agent-bound", "identity.authenticated"]
    return "\n".join(lines), rules


def _content_file(model: M.SystemModel, ids: IdMaps, profile: Profile) -> tuple[str, list[str]]:
    c = profile.content
    rules: list[str] = []
    out: list[str] = []

    def rule(rid: str, nl: str, action: str, body: str, label: str) -> list[str]:
        rules.append(rid)
        return [f"  // @rule {rid}", f"  // @nl {_nl(nl)}", f"  // @on_violation {'DENY' if action == 'deny' else 'FLAG'}",
                f"  {label}: {body};", ""]

    detectors = profile.detector_rules()
    # input
    body: list[str] = []
    if c.prompt_injection.input != "off":
        body += rule("content.input.prompt-injection", "A user message with prompt-injection patterns is "
                     + ("refused before any agent sees it." if c.prompt_injection.input == "deny" else "flagged."),
                     c.prompt_injection.input, "assert never (input_received && input.prompt_injection_detected)",
                     "input_injection")
    for name, d in sorted(detectors.items()):
        if d.input != "off":
            body += rule(f"content.input.{name}", f"A user message containing {name} is "
                         + ("refused." if d.input == "deny" else "flagged."), d.input,
                         f"assert never (input_received && input.contains.{name})", f"input_{name}")
    if c.max_input_chars:
        body += rule("content.input.max-length", f"A user message is at most {c.max_input_chars} characters.",
                     "deny", f"assert never (input_received && input.length > {int(c.max_input_chars)})",
                     "input_length")
    if profile.session.require_session:
        body += rule("content.input.session-required", "Every message belongs to a session.", "deny",
                     "assert always (input_received -> session.present)", "input_session")
    if profile.session.roles:
        roles = " || ".join(f"user.role == {_lit(r)}" for r in profile.session.roles)
        body += rule("content.input.known-role", f"The ingress asserts one of the roles {profile.session.roles}.",
                     "deny", f"assert always (input_received -> ({roles}))", "input_role")
    if body:
        out += _header("User input.", "zt_adk.content.input", "1.0.0", "zt-adk build: zt_adk.yaml content",
                       "native,gateway") + ["vunit content_input (input_message) {", ""] + body + ["}", ""]
    # output
    body = []
    for name, d in sorted(detectors.items()):
        if d.output != "off":
            body += rule(f"content.output.{name}", f"User-visible content containing {name} is "
                         + ("withheld." if d.output == "deny" else "flagged."), d.output,
                         f"assert never (output_emitted && output.contains.{name})", f"output_{name}")
    if body:
        out += _header("User-visible output.", "zt_adk.content.output", "1.0.0", "zt-adk build: zt_adk.yaml content",
                       "native,gateway") + ["vunit content_output (output_message) {", ""] + body + ["}", ""]
    # agent messages
    body = []
    if c.prompt_injection.agent_message != "off":
        body += rule("content.agent-message.prompt-injection", "A request from one agent to another with "
                     "prompt-injection patterns is " + ("refused." if c.prompt_injection.agent_message == "deny"
                                                        else "flagged (the run becomes tainted)."),
                     c.prompt_injection.agent_message,
                     "assert never (agent_message_sent && message.prompt_injection_detected)", "message_injection")
    if body:
        out += _header("Messages between agents.", "zt_adk.content.agent_message", "1.0.0",
                       "zt-adk build: zt_adk.yaml content", "native,gateway") + \
            ["vunit content_agent_message (agent_message) {", ""] + body + ["}", ""]
    # tool results
    body = []
    if c.prompt_injection.tool_result != "off":
        body += rule("content.tool-result.prompt-injection", "A tool result with prompt-injection patterns is "
                     + ("refused before the model sees it." if c.prompt_injection.tool_result == "deny"
                        else "flagged (the run becomes tainted: later side effects need approval)."),
                     c.prompt_injection.tool_result,
                     "assert never (tool_result_received && result.prompt_injection_detected)", "result_injection")
    for name, d in sorted(detectors.items()):
        if d.tool_result != "off":
            body += rule(f"content.tool-result.{name}", f"A tool result containing {name} is "
                         + ("withheld from the model." if d.tool_result == "deny" else "flagged."), d.tool_result,
                         f"assert never (tool_result_received && result.contains.{name})", f"result_{name}")
    if body:
        out += _header("Tool results.", "zt_adk.content.tool_result", "1.0.0", "zt-adk build: zt_adk.yaml content",
                       "native,gateway") + ["vunit content_tool_result (tool_result) {", ""] + body + ["}", ""]
    # tool calls: roles
    body = []
    for key, op in sorted(ids.operations.items()):
        roles = op.get("allowed_roles")
        if roles:
            agent, tool = key.split("/", 1)
            cond = " || ".join(f"user.role == {_lit(r)}" for r in roles)
            body += rule(f"content.tool-call.roles.{_rid(key.replace('/', '.'))}",
                         f"{key} runs only for runs started by the roles {roles}.", "deny",
                         f"assert always (tool_call_requested && tool.agent == {_lit(agent)} && "
                         f"tool.name == {_lit(tool)} -> ({cond}))", f"roles_{len(rules)}")
    if body:
        out += _header("Tool calls and the run's user.", "zt_adk.content.tool_call", "1.0.0",
                       "zt-adk build: zt_adk.yaml tools.<name>.allowed_roles", "native,gateway") + \
            ["vunit content_tool_call (tool_call) {", ""] + body + ["}", ""]
    # model requests: built-in capabilities only for the agents that declare them
    body = []
    builtins: dict[str, list[str]] = {}
    for t in model.tools.values():
        if t.kind == M.BUILTIN:
            builtins.setdefault(t.name, []).append(t.agent)
    body += rule("content.model.declared-functions", "A model request declares only functions the bundle lists "
                 "for the agent (no injected tools).", "deny",
                 "assert never (model_requested && request.undeclared_functions)", "model_functions")
    body += rule("content.model.declared-builtins", "A model request enables only the model-side capabilities of "
                 "the agent's own built-in tools.", "deny",
                 "assert never (model_requested && request.undeclared_builtins)", "model_builtins")
    for name, agents in sorted(builtins.items()):
        if not re.match(r"^[a-z][a-z0-9_]*$", name):
            raise PolicyGenerationError(f"built-in tool name {name!r} is not a field-name segment")
        cond = " || ".join(f"agent.name == {_lit(a)}" for a in sorted(agents))
        body += rule(f"content.model.builtin.{name}", f"Only {sorted(agents)} may use the built-in {name}.", "deny",
                     f"assert always (model_requested && request.builtin.{name} -> ({cond}))", f"builtin_{name}")
    out += _header("Model requests.", "zt_adk.content.model_request", "1.0.0", "zt-adk build: discovered built-ins",
                   "native,gateway") + ["vunit content_model (model_request) {", ""] + body + ["}", ""]
    return "\n".join(out), rules


def _workflow_file(model: M.SystemModel, profile: Profile) -> tuple[str, list[str]]:
    rules: list[str] = []
    body: list[str] = []
    if profile.policies.workflow_order:
        for wf, children in sorted(model.workflows.items()):
            if model.agents[wf].kind != M.SEQUENTIAL or len(children) < 2:
                continue
            for i in range(1, len(children)):
                prev, cur = children[i - 1], children[i]
                rid = f"workflow.order.{_rid(wf)}.{i + 1}"
                rules.append(rid)
                body += [f"  // @rule {rid}",
                         f"  // @nl In a run of {wf}, step {cur} starts only after step {prev} was started by {wf}.",
                         f"  order_{len(rules)}: assert ((agent_routed && route.from == {_lit(wf)} && "
                         f"route.to == {_lit(prev)}) before (agent_routed && route.from == {_lit(wf)} && "
                         f"route.to == {_lit(cur)}));", ""]
    if not body:
        return "", []
    text = "\n".join(_header("Order of workflow steps.", "zt_adk.workflow", "1.0.0",
                             "zt-adk build: sequential workflow agents") +
                     ["vunit workflow_order (workflow_run) {", ""] + body + ["}", ""])
    return text, rules


ROUTE_EDGES = (M.EDGE_TRANSFER, M.EDGE_ORCHESTRATE, M.EDGE_AGENT_TOOL)


def _domain_file(model: M.SystemModel, ids: IdMaps, profile: Profile) -> tuple[str, list[str], list[str]]:
    """policies.deny_cross_domain_routes: a request to start an agent of another domain is denied unless
    the caller is the ingress, the root agent (the application's dispatcher) or a listed exempt caller.
    Returns (text, rule ids, warnings naming every discovered route the rule cuts)."""
    pol = profile.policies
    if not pol.deny_cross_domain_routes:
        if pol.cross_domain_callers:
            raise PolicyGenerationError("policies.cross_domain_callers needs policies.deny_cross_domain_routes: true")
        return "", [], []
    unknown = sorted(set(pol.cross_domain_callers) - set(model.agents))
    if unknown:
        raise PolicyGenerationError(f"policies.cross_domain_callers names unknown agents: {unknown}")
    exempt_agents = sorted({model.root_agent, *pol.cross_domain_callers})
    exempt_subjects = [INGRESS_SUBJECT] + [ids.subject[a] for a in exempt_agents]
    cond = " && ".join(f"subject.id != {_lit(s)}" for s in exempt_subjects)
    rid = "domains.no-cross-domain-routes"
    text = "\n".join(_header("Domain isolation of agent routes.", "zt_adk.domains", "1.0.0",
                             "zt-adk build: zt_adk.yaml policies.deny_cross_domain_routes") + [
        "vunit domains (pdp_request) {", "",
        f"  // @rule {rid}",
        f"  // @nl An agent starts (transfers to, orchestrates or calls as a tool) only agents of its own domain; "
        f"only the ingress and {', '.join(exempt_agents)} start agents of other domains.",
        "  cross_domain_route: assert never (authz_request && resource.target_type == \"subject\"",
        f"      && request.cross_domain && {cond});", "", "}", ""])
    warnings = []
    for e in model.edges:
        if e.kind not in ROUTE_EDGES or e.caller not in model.agents or e.caller in exempt_agents:
            continue
        if e.target in model.agents and ids.domains[e.caller] != ids.domains[e.target]:
            warnings.append(f"{e.kind} route {e.caller} ({ids.domains[e.caller]}) -> {e.target} "
                            f"({ids.domains[e.target]}) is denied by policies.deny_cross_domain_routes")
    return text, [rid], sorted(set(warnings))


def generate_store(model: M.SystemModel, ids: IdMaps, plan: dict[str, Any], profile: Profile, *,
                   approval_issuers: list[str], secondary_issuers: list[str]) -> GeneratedStore:
    store = GeneratedStore()
    catalog, added = build_catalog(model, profile)
    store.argument_fields = added
    store.files["policy_fields.yaml"] = (
        "# Generated by zt-adk build. Part of the signed policy store.\n"
        + yaml.safe_dump(catalog, sort_keys=False, allow_unicode=True))
    for name, (text, rules) in (
        ("00_core.psl", _core_file(model, ids, profile, approval_issuers, secondary_issuers)),
        ("10_access.psl", _access_file(model, ids, plan, profile)),
        ("20_identity.psl", _identity_file()),
        ("30_content.psl", _content_file(model, ids, profile)),
        ("40_workflow.psl", _workflow_file(model, profile)),
    ):
        if text:
            store.files[name] = text
            store.rules[name] = rules
    text, rules, store.warnings = _domain_file(model, ids, profile)
    if text:
        store.files["15_domains.psl"] = text
        store.rules["15_domains.psl"] = rules
    store.files["50_gateway_runtime.psl"] = resources.files("zt_adk").joinpath(
        "resources/gateway_runtime.psl").read_text("utf-8")
    for pattern in profile.policies.overlays:
        matches = sorted(glob.glob(str(profile.path(pattern))))
        if not matches:
            raise PolicyGenerationError(f"policy overlay pattern matches no file: {pattern}")
        for path in matches:
            p = Path(path)
            if p.suffix != ".psl":
                raise PolicyGenerationError(f"policy overlay is not a .psl file: {p}")
            name = f"90_overlay_{p.name}"
            if name in store.files:
                raise PolicyGenerationError(f"two overlays named {p.name}")
            store.files[name] = p.read_text(encoding="utf-8")
    return store


def overlay_matches(name: str, patterns: list[str]) -> bool:
    return any(fnmatch.fnmatch(name, p) for p in patterns)
