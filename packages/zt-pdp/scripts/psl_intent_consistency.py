#!/usr/bin/env python3
"""Consistency check: natural-language intent rules (intent.psl) vs the legitimate graph.

For every placement PEP generator generated for the real MAS (every legitimate route and tool
edge), evaluate every pdp_request intent rule -- including rules marked @disabled -- with
the placement's registry facts. Argument checks are assumed satisfied (well-formed, present,
non-zero, long enough), so any remaining violation is STRUCTURAL: the policy forbids an edge
the deployed MAS uses. Such conflicts must be resolved by the policy owner (fix the data or
the rule); they are the evidence for @disabled annotations.

    python scripts/psl_intent_consistency.py --native-out <native bootstrap output dir>
"""
from __future__ import annotations

import argparse
import json
import re
import sys
from collections import defaultdict
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]

from zt_psl import compile_policy_set                     # noqa: E402
from zt_psl.decision import compile_bool                  # noqa: E402
from zt_psl.fields import Binder, FieldCatalog, atoms_of  # noqa: E402

SATISFIED_ARGS = {"args.well_formed": True, "args.status": "APPROVED", "args.rationale.length": 100,
                  "args.note.nonempty": True, "args.correction_amount.finite_nonzero": True,
                  "args.source_account.nonempty": True, "args.destination_account.nonempty": True,
                  "args.amount.finite_nonzero": True, "args.posting_instructions.nonempty": True}


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--native-out", required=True)
    ap.add_argument("--store", default=str(ROOT / "policy_store"))
    ap.add_argument("--out-md", default=str(ROOT.parents[1] / "docs" / "PSL_INTENT_CONSISTENCY.md"))
    ns = ap.parse_args()
    out = Path(ns.native_out)
    store = Path(ns.store)
    catalog = FieldCatalog.load(store / "policy_fields.yaml")
    text = (store / "intent.psl").read_text(encoding="utf-8")
    enabled_text = re.sub(r"^\s*// @disabled .*\n", "", text, flags=re.M)      # evaluate disabled rules too
    disabled_ids = set(re.findall(r"// @rule (\S+)\n(?:\s*// .*\n)*?\s*// @disabled", text))
    ps = compile_policy_set([("intent.psl", enabled_text)], catalog)
    rules = [r for r in ps.rules if r.scope == "pdp_request" and r.kind == "constraint"]
    sc = catalog.scopes["pdp_request"]
    atoms = []
    for r in rules:
        atoms += atoms_of(r.expr)
    binder = Binder(sc, list(dict.fromkeys(atoms)))
    preds = [(r, compile_bool(r.expr)) for r in rules]

    plan = json.loads((out / "pep_generated" / "generated_pep_plan.json").read_text(encoding="utf-8"))
    ids = {i["canonical_id"]: i for i in yaml.safe_load((out / "pdp_config" / "identities.yaml").read_text(
        encoding="utf-8"))["identities"]}
    res = {r["canonical_id"]: r for r in yaml.safe_load((out / "pdp_config" / "resources.yaml").read_text(
        encoding="utf-8"))["resources"]}
    conflicts: dict[str, list[str]] = defaultdict(list)
    checked = 0
    for p in plan["logical_peps"]:
        s, r = ids.get(p["subject_canonical_id"]), res.get(p["resource_canonical_id"])
        if s is None or r is None:
            continue
        fields = {"subject.id": s["canonical_id"], "subject.runtime_id": s["id"], "subject.domain": s.get("domain") or "",
                  "resource.id": r["canonical_id"], "resource.runtime_id": r["id"], "resource.domain": r.get("domain") or "",
                  "resource.target_type": str((r.get("attributes") or {}).get("scanner_target_type") or ""),
                  "action": p["action"],
                  "request.cross_domain": (s.get("domain") or "") != (r.get("domain") or "")} | SATISFIED_ARGS
        v = binder.bind("authz_request", fields)
        checked += 1
        for rule, f in preds:
            if not f(v):
                conflicts[rule.rule_id].append(f"{p['pep_type']}: {s['id']} -> {r['id']} ({p['action']}) "
                                               f"[{s.get('domain')} -> {r.get('domain')}]")
    lines = ["# Intent rules vs the legitimate MAS graph", "",
             "Generated by `packages/zt-pdp/scripts/psl_intent_consistency.py`. Every PEP generator placement "
             "of the real MAS is evaluated against every `pdp_request` intent rule (disabled rules included), "
             "with argument checks assumed satisfied. A violation means the policy forbids an edge the deployed "
             "system uses.", "",
             f"* placements checked: **{checked}**; intent rules checked: **{len(rules)}**", "",
             "| intent rule | status | conflicting legitimate placements |", "|---|---|---|"]
    for rule, _ in preds:
        n = len(conflicts.get(rule.rule_id, []))
        status = "DISABLED" if rule.rule_id in disabled_ids else "enabled"
        lines.append(f"| `{rule.rule_id}` | {status} | {n} |")
    for rid, items in sorted(conflicts.items()):
        lines += ["", f"## `{rid}` -- {len(items)} conflicts" + (" (rule is disabled)" if rid in disabled_ids else
                                                                  " (RULE IS ENABLED: these edges will be denied)"), ""]
        lines += [f"* {x}" for x in items]
    Path(ns.out_md).write_text("\n".join(lines) + "\n", encoding="utf-8")
    enabled_conflicts = {k: len(v) for k, v in conflicts.items() if k not in disabled_ids}
    print(f"{checked} placements x {len(rules)} rules; conflicts: "
          f"{ {k: len(v) for k, v in conflicts.items()} }; enabled-rule conflicts: {enabled_conflicts}")
    return 1 if enabled_conflicts else 0


if __name__ == "__main__":
    sys.exit(main())
