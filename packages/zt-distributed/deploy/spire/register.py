"""Idempotent SPIRE registration (runs inside the spire-server container).

Reads /etc/spire/entries.json (generated by `prepare` from the deployment descriptor)
and makes the server's entry set for our parent ID exactly match it:
entries are created, or deleted+re-created when selectors/TTL differ.
Usage: python3 register.py [--x509-ttl SECONDS] [--only NAME ...]
"""
from __future__ import annotations

import argparse
import json
import subprocess
import sys

SOCKET = "/tmp/spire-server/private/api.sock"


def spire(*args: str) -> str:
    out = subprocess.run(["spire-server", *args, "-socketPath", SOCKET], capture_output=True, text=True)
    if out.returncode != 0:
        raise RuntimeError(f"spire-server {' '.join(args)} failed: {out.stderr.strip()} {out.stdout.strip()}")
    return out.stdout


def existing(parent: str) -> list[dict]:
    raw = spire("entry", "show", "-parentID", parent, "-output", "json")
    data = json.loads(raw) if raw.strip() else {}
    return data.get("entries") or []


def sel_strings(entry: dict) -> set[str]:
    return {f"{s['type']}:{s['value']}" for s in entry.get("selectors", [])}


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--entries", default="/etc/spire/entries.json")
    ap.add_argument("--x509-ttl", type=int, default=0, help="per-entry X.509-SVID TTL (0 = server default)")
    ns = ap.parse_args()
    wanted = json.load(open(ns.entries))
    parent = wanted[0]["parent_id"]
    have = {e["spiffe_id"]["path"]: e for e in existing(parent)}
    created = updated = unchanged = 0
    report = []
    for w in wanted:
        # spiffe://<trust domain>/<path>: compare by path (the server reports paths per entry)
        path = "/" + w["spiffe_id"].split("://", 1)[1].split("/", 1)[1]
        cur = have.pop(path, None)
        ttl = ns.x509_ttl
        if cur is not None and sel_strings(cur) == set(w["selectors"]) and int(cur.get("x509_svid_ttl") or 0) == ttl:
            unchanged += 1
            report.append({"spiffe_id": w["spiffe_id"], "entry_id": cur["id"], "state": "unchanged"})
            continue
        if cur is not None:
            spire("entry", "delete", "-entryID", cur["id"])
            updated += 1
        args = ["entry", "create", "-parentID", parent, "-spiffeID", w["spiffe_id"], "-output", "json"]
        for s in w["selectors"]:
            args += ["-selector", s]
        if ttl:
            args += ["-x509SVIDTTL", str(ttl)]
        res = json.loads(spire(*args))
        entry_id = res["results"][0]["entry"]["id"]
        created += cur is None
        report.append({"spiffe_id": w["spiffe_id"], "entry_id": entry_id, "selectors": w["selectors"],
                       "x509_svid_ttl": ttl or "server-default", "state": "created" if cur is None else "replaced"})
    for leftover in have.values():                       # entries no longer in the catalog
        spire("entry", "delete", "-entryID", leftover["id"])
    print(json.dumps({"created": created, "replaced": updated, "unchanged": unchanged,
                      "removed": len(have), "entries": report}, indent=1))


if __name__ == "__main__":
    sys.exit(main())
